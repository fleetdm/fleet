#!/bin/bash
# Repackages a fleetd RPM from `fleetctl package --type=rpm` so it can be installed on
# rpm-ostree and bootc hosts (Fedora Atomic desktops, Fedora CoreOS, Bazzite, Bluefin, Aurora).
# fleetd is shipped in /usr/share/factory and copied to /opt/orbit (/var/opt/orbit) at boot.
# Requires rpm-build and cpio. Usage: repackage-fleetd-for-rpm-ostree.sh <fleetd.rpm> [output-dir]

set -euo pipefail

if [ $# -lt 1 ]; then
  echo "Usage: $0 <fleetd.rpm> [output-dir]" >&2
  exit 1
fi
for cmd in rpm rpm2cpio cpio rpmbuild; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "$cmd not found. Install rpm-build and cpio (dnf install rpm-build cpio)." >&2
    exit 1
  fi
done

in=$(realpath "$1")
outdir=$(realpath "${2:-.}")
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

qf() { rpm -qp --qf "$1" "$in" 2>/dev/null; }
name=$(qf '%{NAME}')
version=$(qf '%{VERSION}')
arch=$(qf '%{ARCH}')

mkdir -p "$work/src" "$work/root"
(cd "$work/src" && rpm2cpio "$in" | cpio -idm --quiet)

if [ ! -e "$work/src/opt/orbit/bin/orbit/orbit" ] && [ ! -L "$work/src/opt/orbit/bin/orbit/orbit" ]; then
  echo "$1 isn't a fleetd RPM generated by fleetctl." >&2
  exit 1
fi

root=$work/root
install -d "$root/usr/share/factory/var/opt" "$root/usr/lib/tmpfiles.d" \
  "$root/usr/lib/systemd/system/multi-user.target.wants" "$root/etc/default"
cp -a "$work/src/opt/orbit" "$root/usr/share/factory/var/opt/orbit"
install -m 0600 "$work/src/etc/default/orbit" "$root/etc/default/orbit"
install -m 0644 "$work/src/usr/lib/systemd/system/orbit.service" "$root/usr/lib/systemd/system/orbit.service"
# rpm-ostree doesn't run package scripts against the live system, so enable the service statically.
ln -s ../orbit.service "$root/usr/lib/systemd/system/multi-user.target.wants/orbit.service"

# "C" copies only when /var/opt/orbit is missing or empty, so fleetd's own updates are kept.
cat >"$root/usr/lib/tmpfiles.d/fleetd.conf" <<'EOF'
C /var/opt/orbit
d /var/log/orbit 0755 root root -
d /var/log/osquery 0755 root root -
L /var/usrlocal/bin/orbit - - - - /opt/orbit/bin/orbit/orbit
EOF

cat >"$work/fleetd.spec" <<EOF
%global debug_package %{nil}
%global __os_install_post %{nil}
%global _build_id_links none
%global source_date_epoch_from_changelog 0

Name: $name
Version: $version
Release: 1.ostree
Summary: $(qf '%{SUMMARY}')
License: $(qf '%{LICENSE}')
Vendor: $(qf '%{VENDOR}')
URL: $(qf '%{URL}')
AutoReqProv: no

%description
fleetd repackaged for rpm-ostree and bootc hosts.

%install
cp -a "$root/." "%{buildroot}/"

%files
%config(noreplace) /etc/default/orbit
/usr/lib/systemd/system/orbit.service
/usr/lib/systemd/system/multi-user.target.wants/orbit.service
/usr/lib/tmpfiles.d/fleetd.conf
/usr/share/factory/var/opt/orbit
EOF

rpmbuild -bb --quiet --target "$arch" \
  --define "_topdir $work/rpmbuild" \
  --define "_rpmdir $outdir" \
  --define "_build_name_fmt %%{NAME}-%%{VERSION}-%%{RELEASE}.%%{ARCH}.rpm" \
  "$work/fleetd.spec"

echo "Wrote $outdir/$name-$version-1.ostree.$arch.rpm"
