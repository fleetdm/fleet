// Command fma-script-hashes records the sha256 of every install and uninstall
// script Fleet has published for a Fleet-maintained app, by walking all of the
// manifest history in git up to the given commit.
//
// It feeds the migration that backfills software_installers.install_script_edited
// and uninstall_script_edited: a hash that appears here was published by Fleet,
// anything else was written by an admin.
//
//	go run ./tools/software/fma-script-hashes -to <commit>
package main

import (
	"bufio"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path"
	"sort"
	"strconv"
	"strings"
	"time"

	maintained_apps "github.com/fleetdm/fleet/v4/ee/maintained-apps"
	"github.com/fleetdm/fleet/v4/pkg/file"
)

// written relative to the repository root, so the tool runs from anywhere
const (
	outputDir                = "tools/software/fma-script-hashes"
	installHashMapFile       = "install_script_hash_map.txt"
	uninstallHashMapFile     = "uninstall_script_hash_map.txt"
	generatedByHeaderComment = "# Generated by tools/software/fma-script-hashes. DO NOT EDIT."
	// written where a hash would go, and matched by name in the migration that reads it
	substitutedScriptMarker = "substituted"
)

// contentSHA is git's id for the file's contents, not for any commit.
type manifestRevision struct {
	contentSHA string
	path       string
}

func main() {
	endingCommit := flag.String("to", "", "ending commit; history is read from the beginning up to it")
	flag.Parse()

	if *endingCommit == "" {
		fmt.Fprintln(os.Stderr, "-to is required")
		flag.Usage()
		os.Exit(1)
	}

	err := generateHashMaps(*endingCommit)
	if err != nil {
		fmt.Fprintf(os.Stderr, "%v\n", err)
		os.Exit(1)
	}
}

func generateHashMaps(endingCommit string) error {
	repoRoot, err := git("rev-parse", "--show-toplevel")
	if err != nil {
		return err
	}

	// resolves a branch, tag or short sha to a full one, and fails here rather than
	// producing a half-empty file if the commit doesn't exist
	endingCommitSHA, err := git("rev-parse", endingCommit+"^{commit}")
	if err != nil {
		return err
	}
	// the ending commit's date becomes the cutoff the migration compares against
	// software_installers.updated_at. UTC so the file doesn't vary by timezone.
	committed, err := git("log", "-1", "--format=%cI", endingCommitSHA)
	if err != nil {
		return err
	}
	commitDate, err := time.Parse(time.RFC3339, committed)
	if err != nil {
		return fmt.Errorf("parsing commit date %q: %w", committed, err)
	}
	cutoffDate := commitDate.UTC().Format(time.RFC3339)

	revisions, err := findManifestRevisions(endingCommitSHA)
	if err != nil {
		return err
	}

	install, uninstall, err := hashScripts(revisions)
	if err != nil {
		return err
	}

	err = writeHashMap(repoRoot, installHashMapFile, endingCommitSHA, cutoffDate, install)
	if err != nil {
		return err
	}
	err = writeHashMap(repoRoot, uninstallHashMapFile, endingCommitSHA, cutoffDate, uninstall)
	if err != nil {
		return err
	}

	fmt.Printf("read %d manifest revisions: %d install entries, %d uninstall entries\n", len(revisions), len(install), len(uninstall))
	return nil
}

func writeHashMap(repoRoot string, name string, endingCommitSHA string, cutoffDate string, lines []string) error {
	var out strings.Builder
	fmt.Fprintln(&out, generatedByHeaderComment)
	fmt.Fprintf(&out, "# to %s %s\n", endingCommitSHA, cutoffDate)
	for _, line := range lines {
		fmt.Fprintln(&out, line)
	}

	err := os.WriteFile(path.Join(repoRoot, outputDir, name), []byte(out.String()), 0o644)
	if err != nil {
		return fmt.Errorf("writing %s: %w", name, err)
	}
	fmt.Printf("wrote %s\n", path.Join(outputDir, name))
	return nil
}

func findManifestRevisions(endingCommit string) (map[manifestRevision]struct{}, error) {
	revisions := map[manifestRevision]struct{}{}

	// one line per changed file, with --format= dropping the commit lines. Merge
	// commits emit nothing, and the commits they merge are walked anyway.
	changed, err := git("log", "--raw", "--no-renames", "--no-abbrev", "--format=", endingCommit, "--", maintained_apps.OutputPath)
	if err != nil {
		return nil, err
	}
	for line := range strings.SplitSeq(changed, "\n") {
		if !strings.HasPrefix(line, ":") {
			continue
		}
		modesAndSHAs, filePath, found := strings.Cut(line, "\t")
		if !found {
			continue
		}
		// the fourth field is what the file became; the third is what it was
		if fields := strings.Fields(modesAndSHAs); len(fields) >= 4 {
			addManifestRevision(revisions, fields[3], filePath)
		}
	}

	return revisions, nil
}

func addManifestRevision(revisions map[manifestRevision]struct{}, contentSHA string, filePath string) {
	// an all-zero sha is a delete, and apps.json is the app list, not a manifest
	deleted := strings.Trim(contentSHA, "0") == ""
	if deleted || path.Base(filePath) == "apps.json" || !strings.HasSuffix(filePath, ".json") {
		return
	}
	revisions[manifestRevision{contentSHA: contentSHA, path: filePath}] = struct{}{}
}

type scriptHash struct {
	slug string
	hash string
}

// Returns "<sha256> <slug>" lines. Scripts are hashed exactly as published: every
// release is in here, so a script naming the installer file matches on its own.
func hashScripts(revisions map[manifestRevision]struct{}) (install []string, uninstall []string, err error) {
	reader, err := startCatFile()
	if err != nil {
		return nil, nil, err
	}

	installHashes := map[scriptHash]struct{}{}
	uninstallHashes := map[scriptHash]struct{}{}
	for revision := range revisions {
		contents, err := reader.readFile(revision.contentSHA)
		if err != nil {
			return nil, nil, fmt.Errorf("reading %s at %s: %w", revision.path, revision.contentSHA, err)
		}

		var manifest maintained_apps.FMAManifestFile
		err = json.Unmarshal(contents, &manifest)
		if err != nil {
			return nil, nil, fmt.Errorf("parsing %s at %s: %w", revision.path, revision.contentSHA, err)
		}

		slug := slugFromPath(revision.path)
		if slug == "" {
			continue
		}
		for _, version := range manifest.Versions {
			if script := manifest.Refs[version.InstallScriptRef]; script != "" {
				installHashes[scriptHash{slug, hashScript(script)}] = struct{}{}
			}
			if script := manifest.Refs[version.UninstallScriptRef]; script != "" {
				uninstallHashes[scriptHash{slug, uninstallScriptHash(script)}] = struct{}{}
			}
		}
	}

	err = reader.close()
	if err != nil {
		return nil, nil, err
	}

	return hashMapLines(installHashes), hashMapLines(uninstallHashes), nil
}

// sorted by app rather than by the line, which starts with the hash.
func hashMapLines(hashes map[scriptHash]struct{}) []string {
	sorted := make([]scriptHash, 0, len(hashes))
	for hash := range hashes {
		sorted = append(sorted, hash)
	}
	sort.Slice(sorted, func(i int, j int) bool {
		if sorted[i].slug != sorted[j].slug {
			return sorted[i].slug < sorted[j].slug
		}
		return sorted[i].hash < sorted[j].hash
	})

	lines := make([]string, 0, len(sorted))
	for _, hash := range sorted {
		lines = append(lines, fmt.Sprintf("%s %s", hash.hash, hash.slug))
	}
	return lines
}

// one long-lived process, since there are tens of thousands of files to read.
type catFile struct {
	cmd   *exec.Cmd
	stdin io.WriteCloser
	out   *bufio.Reader
}

func startCatFile() (*catFile, error) {
	cmd := exec.Command("git", "cat-file", "--batch")
	cmd.Stderr = os.Stderr
	stdin, err := cmd.StdinPipe()
	if err != nil {
		return nil, err
	}
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		return nil, err
	}
	err = cmd.Start()
	if err != nil {
		return nil, fmt.Errorf("starting git cat-file: %w", err)
	}
	return &catFile{cmd: cmd, stdin: stdin, out: bufio.NewReader(stdout)}, nil
}

// git answers with a "<sha> <type> <size>" line, then that many bytes, then a newline.
func (c *catFile) readFile(contentSHA string) ([]byte, error) {
	_, err := io.WriteString(c.stdin, contentSHA+"\n")
	if err != nil {
		return nil, err
	}

	header, err := c.out.ReadString('\n')
	if err != nil {
		return nil, err
	}
	fields := strings.Fields(header)
	if len(fields) != 3 {
		return nil, fmt.Errorf("unexpected cat-file header %q", strings.TrimSpace(header))
	}
	size, err := strconv.Atoi(fields[2])
	if err != nil {
		return nil, fmt.Errorf("unexpected cat-file size in %q", strings.TrimSpace(header))
	}

	contents := make([]byte, size)
	_, err = io.ReadFull(c.out, contents)
	if err != nil {
		return nil, err
	}
	_, err = c.out.Discard(1)
	if err != nil {
		return nil, err
	}
	return contents, nil
}

func (c *catFile) close() error {
	err := c.stdin.Close()
	if err != nil {
		return err
	}
	err = c.cmd.Wait()
	if err != nil {
		return fmt.Errorf("git cat-file: %w", err)
	}
	return nil
}

// slugFromPath turns a manifest path into the app's slug, which is always
// "<app>/<platform>". Manifests were laid out as outputs/<platform>/<app>.json
// before March 2025 and outputs/<app>/<platform>.json since.
func slugFromPath(filePath string) string {
	rel := strings.TrimPrefix(filePath, maintained_apps.OutputPath+"/")
	rel = strings.TrimSuffix(rel, ".json")
	first, second, found := strings.Cut(rel, "/")
	if !found {
		return ""
	}
	if first == "darwin" || first == "windows" {
		return second + "/" + first
	}
	return first + "/" + second
}

func hashScript(script string) string {
	sum := sha256.Sum256([]byte(script))
	return hex.EncodeToString(sum[:])
}

// uninstallScriptHash marks apps whose uninstall script gets substituted with
// installer metadata, since the value can't be derived from the manifest and we
// can't know whether those were changed. The migration marks them as unedited.
func uninstallScriptHash(script string) string {
	if file.PackageIDRegex.MatchString(script) || file.UpgradeCodeRegex.MatchString(script) {
		return substitutedScriptMarker
	}
	return hashScript(script)
}

func git(args ...string) (string, error) {
	cmd := exec.Command("git", args...)
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("git %s: %w", strings.Join(args, " "), err)
	}
	return strings.TrimSpace(string(out)), nil
}
