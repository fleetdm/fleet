func TestUp_20260824183354(t *testing.T) {
	db := applyUpToPrev(t)

	// A published Fleet script for each of two apps, plus one that only matches
	// after the installer filename is substituted the way the auto-update cron
	// used to substitute it before comparing.
	const (
		publishedInstall     = "#!/bin/sh\ninstaller -pkg app.pkg\n"
		publishedUninstall   = "#!/bin/sh\nrm -rf /Applications/App.app\n"
		versionedInstall     = "#!/bin/sh\ninstaller -pkg \"$TMPDIR/app-1.0.pkg\"\n"
		normalizedInstall    = "#!/bin/sh\ninstaller -pkg \"$TMPDIR/__FLEET_INSTALLER_FILE__\"\n"
		adminInstall   = "#!/bin/sh\necho custom install\n"
		adminUninstall = "#!/bin/sh\necho custom uninstall\n"
		// Rows are pinned to beforeCutoff so they fall inside the window the corpus
		// can speak to, since a freshly inserted row would otherwise be stamped now.
		corpusCutoff = "2026-08-01T00:00:00Z"
		beforeCutoff = "2026-07-01 00:00:00"
		afterCutoff  = "2026-08-15 12:00:00"
	)

	// The migration reads the corpus generated by tools/fma-script-hashes. Swap in a
	// small one so the test states its own expectations instead of depending on
	// which scripts Fleet happened to publish.
	restore := fmaScriptHashes
	t.Cleanup(func() { fmaScriptHashes = restore })
	fmaScriptHashes = fmt.Sprintf(`# Generated by tools/fma-script-hashes. DO NOT EDIT.
# from aaaaaaaa
# to bbbbbbbb %s
i chess/darwin %s
i chess/darwin %s
u chess/darwin %s
i checkers/darwin %s
u checkers/darwin %s
`,
		corpusCutoff,
		sha256Hex(publishedInstall),
		sha256Hex(normalizedInstall),
		sha256Hex(publishedUninstall),
		sha256Hex(publishedInstall),
		sha256Hex(publishedUninstall),
	)

	// script_contents is deduplicated by content, so the same script shared by two
	// installers resolves to the row that already holds it.
	scriptID := func(contents string) int64 {
		return execNoErrLastID(t, db, `
			INSERT INTO script_contents (contents, md5_checksum) VALUES (?, UNHEX(MD5(?)))
			ON DUPLICATE KEY UPDATE id = LAST_INSERT_ID(id)`, contents, contents)
	}
	maintainedAppID := func(slug string) int64 {
		return execNoErrLastID(t, db,
			`INSERT INTO fleet_maintained_apps (name, slug, platform, unique_identifier) VALUES (?, ?, 'darwin', ?)`,
			slug, slug, slug)
	}
	insertInstaller := func(name string, teamID int64, fmaID any, filename string, install string, uninstall string) int64 {
		titleID := execNoErrLastID(t, db,
			`INSERT INTO software_titles (name, source) VALUES (?, 'apps')`, name)
		return execNoErrLastID(t, db, `
			INSERT INTO software_installers
				(team_id, global_or_team_id, title_id, filename, extension, version, platform,
				 install_script_content_id, uninstall_script_content_id, storage_id,
				 package_ids, patch_query, fleet_maintained_app_id)
			VALUES (NULL, ?, ?, ?, 'pkg', '1.0', 'darwin', ?, ?, ?, '', '', ?)`,
			teamID, titleID, filename, scriptID(install), scriptID(uninstall), filename, fmaID)
	}

	chess := maintainedAppID("chess/darwin")
	checkers := maintainedAppID("checkers/darwin")

	// No team (global_or_team_id 0), everything as Fleet published it.
	untouched := insertInstaller("Untouched", 0, chess, "app.pkg", publishedInstall, publishedUninstall)
	// Only the install script was replaced.
	installEdited := insertInstaller("Install edited", 0, chess, "app.pkg", adminInstall, publishedUninstall)
	// Both scripts replaced, on a team rather than no-team.
	bothEdited := insertInstaller("Both edited", 1, chess, "app.pkg", adminInstall, adminUninstall)
	// Matches only once the versioned installer filename is substituted.
	needsNormalizing := insertInstaller("Needs normalizing", 0, chess, "app-1.0.pkg", versionedInstall, publishedUninstall)
	// A published script, but belonging to a different app than the one it was published for.
	wrongApp := insertInstaller("Wrong app", 0, checkers, "app.pkg", versionedInstall, publishedUninstall)
	// Changed after the corpus was cut, so the corpus can't speak to it.
	changedAfterCutoff := insertInstaller("Changed after cutoff", 0, chess, "app.pkg", adminInstall, adminUninstall)
	// Not a Fleet-maintained app at all.
	notMaintained := insertInstaller("Not maintained", 0, nil, "custom.pkg", adminInstall, adminUninstall)

	execNoErr(t, db, `UPDATE software_installers SET updated_at = ?`, beforeCutoff)
	execNoErr(t, db, `UPDATE software_installers SET updated_at = ? WHERE id = ?`,
		afterCutoff, changedAfterCutoff)

	// Apply current migration.
	applyNext(t, db)

	flags := func(id int64) (install bool, uninstall bool) {
		var row struct {
			Install   bool `db:"install_script_edited"`
			Uninstall bool `db:"uninstall_script_edited"`
		}
		require.NoError(t, db.Get(&row,
			`SELECT install_script_edited, uninstall_script_edited FROM software_installers WHERE id = ?`, id))
		return row.Install, row.Uninstall
	}

	install, uninstall := flags(untouched)
	require.False(t, install)
	require.False(t, uninstall)

	install, uninstall = flags(installEdited)
	require.True(t, install)
	require.False(t, uninstall)

	install, uninstall = flags(bothEdited)
	require.True(t, install)
	require.True(t, uninstall)

	install, uninstall = flags(needsNormalizing)
	require.False(t, install, "a script matching after filename substitution was not edited")
	require.False(t, uninstall)

	install, _ = flags(wrongApp)
	require.True(t, install, "a script published for another app doesn't count as this app's")

	install, uninstall = flags(changedAfterCutoff)
	require.False(t, install, "rows changed after the corpus cutoff keep the default")
	require.False(t, uninstall)

	install, uninstall = flags(notMaintained)
	require.False(t, install)
	require.False(t, uninstall)

	// New rows default to not-edited.
	fresh := insertInstaller("Fresh", 0, chess, "fresh.pkg", adminInstall, adminUninstall)
	install, uninstall = flags(fresh)
	require.False(t, install)
	require.False(t, uninstall)
}

// TestFMAScriptHashesFile checks the artifact tools/fma-script-hashes generates,
// since the migration above runs against a stand-in corpus.
func TestFMAScriptHashesFile(t *testing.T) {
	install, uninstall, toDate, err := parseFMAScriptHashes(fmaScriptHashes)
	require.NoError(t, err)
	require.NotEmpty(t, toDate)
	require.NotEmpty(t, install)
	require.NotEmpty(t, uninstall)

	// Every Fleet-maintained app publishes both scripts, so a lopsided corpus means
	// the generator dropped something.
	require.Greater(t, len(install), len(uninstall))
}

func sha256Hex(contents string) string {
	sum := sha256.Sum256([]byte(contents))
	return hex.EncodeToString(sum[:])
}
