func TestScriptHashMapFiles(t *testing.T) {
	read := func(name string) (scriptHashMap, time.Time) {
		contents, err := os.ReadFile(filepath.Join("..", "..", "..", "..", "..", "tools", "software", "fma-script-hashes", name))
		require.NoError(t, err)
		hashes, toDate, err := parseScriptHashMap(string(contents))
		require.NoError(t, err)
		require.False(t, toDate.IsZero())
		require.NotEmpty(t, hashes)
		return hashes, toDate
	}

	install, installCutoff := read(installScriptHashMapFile)
	uninstall, uninstallCutoff := read(uninstallScriptHashMapFile)

	// both files come out of one run, so a mismatched cutoff means they were
	// regenerated separately and no longer describe the same history
	require.Equal(t, installCutoff, uninstallCutoff)

	// every line holds either a sha256 or the word "substituted". The generator writes
	// that word and this migration looks it up, and neither reads the other's copy of
	// it, so renaming one side has to fail here rather than in production.
	substituted := 0
	for _, hashes := range []scriptHashMap{install, uninstall} {
		for key := range hashes {
			hash, _, found := strings.Cut(key, " ")
			require.True(t, found)
			if len(hash) == 2*sha256.Size {
				continue
			}
			require.Equal(t, substitutedScriptMarker, hash)
			substituted++
		}
	}
	require.NotZero(t, substituted, "some uninstall scripts get substituted, so the word should appear")

	// every app publishes both scripts, so a slug in one file and not the other
	// means the generator dropped one kind for that app
	slugs := func(hashes scriptHashMap) map[string]struct{} {
		apps := map[string]struct{}{}
		for key := range hashes {
			_, slug, found := strings.Cut(key, " ")
			require.True(t, found)
			apps[slug] = struct{}{}
		}
		return apps
	}
	require.Equal(t, slugs(install), slugs(uninstall))
}

// A hash map that arrives truncated or malformed has to stop the migration, since
// carrying on would read every installer as unedited.
func TestParseScriptHashMapRejectsBadInput(t *testing.T) {
	const header = "# Generated by tools/software/fma-script-hashes. DO NOT EDIT.\n# to abcd1234 2026-08-01T00:00:00Z\n"

	for _, tc := range []struct {
		name     string
		contents string
		wantErr  string
	}{
		{"no header", "# Generated by tools/software/fma-script-hashes. DO NOT EDIT.", "too short"},
		{"header is not the cutoff line", "# Generated\n# from abcd1234\n", `expected a "# to <commit> <date>" header`},
		{"cutoff is not a date", "# Generated\n# to abcd1234 last-tuesday\n", "parsing cutoff"},
		{"entry missing its slug", header + "abc123\n", `unexpected line "abc123"`},
		{"entry with a spare field", header + "abc123 foo/darwin extra\n", "unexpected line"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, _, err := parseScriptHashMap(tc.contents)
			require.ErrorContains(t, err, tc.wantErr)
		})
	}

	hashes, cutoff, err := parseScriptHashMap(header + "abc123 foo/darwin\nabc123 bar/darwin\n")
	require.NoError(t, err)
	require.Equal(t, "2026-08-01T00:00:00Z", cutoff.Format(time.RFC3339))
	require.Len(t, hashes, 2)
	_, found := hashes["abc123 foo/darwin"]
	require.True(t, found)
}

func sha256Hex(contents string) string {
	sum := sha256.Sum256([]byte(contents))
	return hex.EncodeToString(sum[:])
}
