import React from "react";

import CustomLink from "components/CustomLink";
import Checkbox from "components/forms/fields/Checkbox";
import GitOpsModeTooltipWrapper from "components/GitOpsModeTooltipWrapper";
import SettingsSection from "pages/admin/components/SettingsSection";

import { IAdvancedSectionProps } from "../../Advanced";

const FeaturesSection = ({
  formData,
  onInputChange,
  isPremiumTier = false,
}: IAdvancedSectionProps) => {
  const {
    disableLiveQuery,
    disableScripts,
    disableAIFeatures,
    enableProfileValidation,
    disableMCP,
  } = formData;
  // The configuration profile builder is hidden until the AI features are
  // released, and so is its mention here.
  const showAIProfileBuilder = featureFlags.showAIProfileBuilder === "true";

  return (
    <SettingsSection title="Features">
      <GitOpsModeTooltipWrapper
        position="left"
        renderChildren={(disableChildren) => (
          <Checkbox
            disabled={disableChildren}
            onChange={() =>
              onInputChange({
                name: "disableLiveQuery",
                value: !disableLiveQuery,
              })
            }
            name="disableLiveQuery"
            value={!disableLiveQuery}
            labelTooltipContent={
              !disableChildren && (
                <>
                  When disabled, removes the ability to run live reports (ad hoc
                  reports executed via the UI or fleetctl).
                  <br />
                  <i>
                    (Default: <strong>On</strong>)
                  </i>
                </>
              )
            }
          >
            Live reports
          </Checkbox>
        )}
      />

      <GitOpsModeTooltipWrapper
        position="left"
        renderChildren={(disableChildren) => (
          <Checkbox
            disabled={disableChildren}
            onChange={() =>
              onInputChange({ name: "disableScripts", value: !disableScripts })
            }
            name="disableScripts"
            value={!disableScripts}
            labelTooltipContent={
              !disableChildren && (
                <>
                  Disabling script execution will block access to run scripts.
                  Scripts may still be added and removed in the UI and API.
                  Features that run scripts under-the-hood (e.g. software
                  install, lock/wipe, script-only packages) will still be
                  available.
                  <br />
                  <i>
                    (Default: <b>On</b>)
                  </i>
                </>
              )
            }
          >
            Script execution
          </Checkbox>
        )}
      />
      <GitOpsModeTooltipWrapper
        position="left"
        renderChildren={(disableChildren) => (
          <Checkbox
            disabled={disableChildren}
            onChange={() =>
              onInputChange({
                name: "disableAIFeatures",
                value: !disableAIFeatures,
              })
            }
            name="disableAIFeatures"
            value={!disableAIFeatures}
            labelTooltipContent={
              !disableChildren && (
                <>
                  {showAIProfileBuilder ? (
                    <>
                      When disabled, removes AI features that generate policy
                      descriptions, policy resolutions, and configuration
                      profiles.
                    </>
                  ) : (
                    <>
                      When disabled, removes AI features such as pre-filling
                      forms with descriptions generated by a large language
                      model (LLM).
                    </>
                  )}{" "}
                  <br />
                  <i>
                    (Default: <strong>On</strong>)
                  </i>
                </>
              )
            }
            helpText={
              showAIProfileBuilder
                ? "Only policy queries (SQL) and profile prompts are sent to the LLM. Fleet doesn't use this data to train models."
                : "When enabled, only policy queries (SQL) are sent to the LLM. Fleet doesn't use this data to train models."
            }
          >
            Generative AI
          </Checkbox>
        )}
      />
      <GitOpsModeTooltipWrapper
        position="left"
        renderChildren={(disableChildren) => (
          <Checkbox
            disabled={disableChildren}
            onChange={() =>
              onInputChange({
                name: "enableProfileValidation",
                value: !enableProfileValidation,
              })
            }
            name="enableProfileValidation"
            value={enableProfileValidation}
            labelTooltipContent={
              !disableChildren && (
                <>
                  Currently supported for Apple and Windows configuration
                  profiles. When disabled, Fleet does not check that each
                  setting it recognizes has a value of the expected type.
                  <br />
                  <i>
                    (Default: <strong>On</strong>)
                  </i>
                </>
              )
            }
          >
            Profile validation
          </Checkbox>
        )}
      />
      {isPremiumTier && (
        <GitOpsModeTooltipWrapper
          position="left"
          renderChildren={(disableChildren) => (
            <Checkbox
              disabled={disableChildren}
              onChange={() =>
                onInputChange({ name: "disableMCP", value: !disableMCP })
              }
              name="disableMCP"
              value={!disableMCP}
              labelTooltipContent={
                !disableChildren && (
                  <>
                    When disabled, AI harnesses (e.g. Claude) can&apos;t connect
                    to Fleet&apos;s MCP server.
                    <br />
                    <i>
                      (Default: <strong>On</strong>)
                    </i>
                  </>
                )
              }
              helpText={
                <>
                  Connect Fleet&apos;s MCP server to your AI harness (Claude,
                  Codex, Copilot, etc.) so that you can ask questions about your
                  fleet.{" "}
                  <CustomLink
                    url="https://fleetdm.com/guides/fleet-mcp"
                    text="Learn more"
                    newTab
                  />
                </>
              }
            >
              MCP server
            </Checkbox>
          )}
        />
      )}
    </SettingsSection>
  );
};

export default FeaturesSection;
